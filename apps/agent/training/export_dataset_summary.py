"""Export the synthetic dataset's shape for the public /data surface (FR-031).

Run:  .venv/bin/python training/export_dataset_summary.py

Everything SandScope reasons about is invented — the company, its services, its
incidents, its documents. That is stated on the site, and until now it was only
stated. A reader had no way to see WHAT was invented, how much of it there is,
or how the 715 evaluation questions were built. "Synthetic" without an
inventory is indistinguishable from "vague".

This writes that inventory. It runs in Python because the estate, the fault
patterns and the question generators live here; the web build has no Python, so
the output is committed and `test_dataset_summary_is_current` fails the build if
the committed file no longer matches what this script produces. That mirrors the
existing reliability.json arrangement, and it is the only thing that keeps a
published inventory from quietly describing a corpus that has moved on.

No model is called. Nothing here is generated by an LLM.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from sandscope_agent.evaluation.dataset import Label, build_dataset
from sandscope_agent.retrieval.corpus import chunk_corpus, load_corpus
from sandscope_agent.seed import estate
from sandscope_agent.seed.faults import PATTERNS

OUT = Path(__file__).resolve().parents[2] / "web" / "src" / "generated" / "dataset.json"

#: What each generation mechanism actually does, in a sentence a non-specialist
#: can hold. Written here rather than on the page so the explanation travels
#: with the mechanism it describes.
MECHANISM_NOTES: dict[str, str] = {
    "symptom_from_fault_signal": (
        "Takes a real metric from a fault pattern and asks about it the way an on-call "
        "engineer would. Answerable because the runbook for that fault is in the corpus."
    ),
    "question_from_any_section_heading": (
        "Turns a heading in a document into the question that heading answers. Answerable "
        "by construction — the section IS the answer."
    ),
    "section_from_runbook_heading": (
        "The same idea narrowed to runbooks, where headings are procedural steps."
    ),
    "policy_value_lookup": (
        "Asks for a specific number a policy states — a severity level, an escalation timer. "
        "The hardest answerable kind, because a near-miss reads as correct."
    ),
    "property_documented_for_another_entity": (
        "The sharpest trick in the set. Takes a property the corpus documents for ONE service "
        "and asks it of a different service. Retrieval happily returns the passage about the "
        "wrong service, so a weak system answers confidently with a real number that is about "
        "something else."
    ),
    "entity_cannot_exhibit_this_fault": (
        "Asks about a fault a given service physically cannot have — a memory-leak metric on a "
        "gateway that does not run that way. Plausible-sounding, ungrounded."
    ),
    "topic_absent_from_corpus": (
        "Topics deliberately left out of the corpus entirely, listed in GAPS.md. Absence is "
        "VERIFIED against the text, not assumed."
    ),
}


def main() -> None:
    documents = load_corpus()
    chunks = chunk_corpus(documents)
    questions = build_dataset().all
    services = estate.services()
    dependencies = estate.dependencies()

    by_mechanism = Counter(q.mechanism for q in questions)
    labels_per_mechanism = {
        mech: Counter(q.label.value for q in questions if q.mechanism == mech)
        for mech in by_mechanism
    }

    # One real example per mechanism, so a reader can judge the trick rather
    # than take the description on trust.
    example: dict[str, str] = {}
    for question in questions:
        example.setdefault(str(question.mechanism), question.text)

    payload = {
        "corpus": {
            "documents": len(documents),
            "chunks": len(chunks),
            "words": sum(len(d.body.split()) for d in documents),
            "byKind": dict(Counter(d.id.split("-")[0] for d in documents)),
            "files": sorted(
                (
                    {
                        "id": d.id,
                        "title": d.title,
                        "words": len(d.body.split()),
                        "chunks": sum(1 for c in chunks if c.document_id == d.id),
                    }
                    for d in documents
                ),
                key=lambda row: str(row["id"]),
            ),
        },
        "estate": {
            "services": len(services),
            "dependencies": len(dependencies),
            "byTier": {
                str(int(t)): n for t, n in sorted(Counter(s.tier for s in services).items())
            },
            "teams": sorted({s.owner_team for s in services}),
            "runtimes": sorted({s.runtime for s in services}),
            "region": sorted({s.region for s in services}),
            "rows": [
                {
                    "id": s.id,
                    "name": s.name,
                    "tier": int(s.tier),
                    "runtime": s.runtime,
                    "team": s.owner_team,
                }
                for s in services
            ],
        },
        "faults": [
            {
                "id": p.id,
                "name": p.name,
                "severity": p.severity,
                "runbook": p.runbook_id,
                "signals": [s.metric for s in p.primary],
                "summary": p.summary,
            }
            for p in PATTERNS
        ],
        "questions": {
            "total": len(questions),
            "answerable": sum(1 for q in questions if q.label is Label.ANSWERABLE),
            "unanswerable": sum(1 for q in questions if q.label is not Label.ANSWERABLE),
            "mechanisms": [
                {
                    "id": str(mech),
                    "count": count,
                    "label": (
                        "answerable"
                        if labels_per_mechanism[mech].get("answerable")
                        else "unanswerable"
                    ),
                    "note": MECHANISM_NOTES.get(str(mech), ""),
                    "example": example.get(str(mech), ""),
                }
                for mech, count in by_mechanism.most_common()
            ],
        },
    }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    q = payload["questions"]
    print(
        f"exported {payload['corpus']['documents']} documents · "
        f"{payload['estate']['services']} services · {len(payload['faults'])} fault patterns · "
        f"{q['total']} questions ({q['answerable']} answerable / {q['unanswerable']} not)"
    )


if __name__ == "__main__":
    main()
